const missing = ICONS.filter((name) => !set.icons[name]);
if (missing.length > 0) {
    console.error(`Missing game-icons: ${missing.join(', ')}`);
    process.exit(1);
}

const entries = ICONS.map((name) => {
    // Every game-icons body is a single <path> with fill="currentColor" on a 512x512 canvas;
    // keep only the `d` attribute so callers can style the fill freely.
    const match = /\sd="([^"]+)"/.exec(set.icons[name].body);
    if (!match) throw new Error(`Unexpected body for ${name}`);
    return `    '${name}': '${match[1]}',`;
});

const output = `// GENERATED by scripts/generate-icons.mjs - do not edit by hand.
// Icons by Lorc, Delapouite and contributors - https://game-icons.net - CC BY 3.0.

export const ICON_PATHS = {
${entries.join('\n')}
} as const;

export type IconName = keyof typeof ICON_PATHS;

/** All icons share this square canvas. */
export const ICON_VIEWBOX = 512;
`;

writeFileSync(join(here, '..', 'src', 'icons.generated.ts'), output);
console.warn(`Wrote ${ICONS.length} icons.`);
