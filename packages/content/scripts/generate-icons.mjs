// Extracts only the game-icons.net glyphs Kardux actually uses (CC BY 3.0, see README.md)
// into a small, typed TypeScript module - the full set is 4000+ icons / several MB, far too
// much to ship to the browser. Run with `pnpm --filter @kardux/content icons` after editing
// the list below; the output file is committed so builds never depend on this script.
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const here = dirname(fileURLToPath(import.meta.url));
const set = JSON.parse(
    readFileSync(require.resolve('@iconify-json/game-icons/icons.json'), 'utf8'),
);

